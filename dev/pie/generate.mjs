// Generate the fixed terminal geometry only. No session data is needed at build time.
import { Surface, arc } from 'ascii.rest/kit';
import { writeFileSync } from 'node:fs';

const cols = 18, rows = 8, grid = new Surface(cols, rows);
const turns = 360;
for (let d = 0; d < turns; d++) {
  const ch = String.fromCharCode(0xe000 + d);
  arc(grid, cols / 2, rows / 2, 8, d / turns, (d + 1) / turns, { char: ch, fill: ch });
}
const matrix = Array.from({ length: rows }, (_, y) =>
  Array.from({ length: cols }, (_, x) => {
    const ch = grid.get(x, y);
    return ch ? ch.charCodeAt(0) - 0xe000 : -1;
  }));
writeFileSync(new URL('../../clean_my_agent/_pie_grid.py', import.meta.url),
  '# Generated by dev/pie/generate.mjs with ascii.rest/kit arc().\n' +
  '# Clockwise degrees per character cell; -1 is outside the pie.\n' +
  'DEGREES = (\n' + matrix.map(row => '    (' + row.join(', ') + '),').join('\n') + '\n)\n');
